export function specialById(id) {
  return SPECIALS.find((item) => item.id === id) || null;
}

export function eventFromRoll(roll) {
  const value = ((roll - 1) % 100) + 1;
  return EVENTS.find((item) => value >= item.min && value <= item.max) || EVENTS[0];
}

export function specialCap(level) {
  if (level < 5) return 0;
  if (level < 9) return 2;
  if (level < 13) return 4;
  if (level < 17) return 5;
  return 6;
}

export function buyLimitGp(level) {
  if (level >= 13) return 5000;
  if (level >= 9) return 2000;
  return 500;
}

/** Extra portion paid above list price, in basis points. 1000 = 10%. */
export function sellMarginBps(level) {
  if (level >= 17) return 10000;
  if (level >= 13) return 5000;
  if (level >= 9) return 2000;
  return 1000;
}

export function saleProceeds(standardGp, level) {
  return Math.round((standardGp * (10000 + sellMarginBps(level))) / 10000);
}
